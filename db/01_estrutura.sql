-- =====================================================================
-- Rotalume · People Analytics
-- 01 · Estrutura das tabelas
--
-- Esquemas:
--   rh          dados de RH (colaboradores, ausências, pesquisa de clima)
--   app         usuários do painel, log de acessos, tentativas de login
--   app_privado segredo do token e parâmetros da simulação (ninguém lê)
--   api         a única "porta" que o aplicativo usa: views e funções
-- =====================================================================

create extension if not exists pgcrypto;

create schema if not exists rh;
create schema if not exists app;
create schema if not exists app_privado;
create schema if not exists api;

-- ---------------------------------------------------------------------
-- Cadastros
-- ---------------------------------------------------------------------
create table rh.diretorias (
  id   smallint primary key,
  nome text not null
);

create table rh.unidades (
  id   smallint primary key,
  nome text not null
);

create table rh.areas (
  id           smallint primary key,
  nome         text not null,
  diretoria_id smallint not null references rh.diretorias
);

create table rh.niveis (
  id   smallint primary key,
  nome text not null
);

-- ---------------------------------------------------------------------
-- Colaboradores (dados pessoais e sensíveis: CPF, nascimento, salário)
-- ---------------------------------------------------------------------
create table rh.colaboradores (
  id                int generated by default as identity primary key,
  nome              text not null,
  cpf               text not null,          -- fictício e propositalmente inválido
  genero            char(1) not null check (genero in ('F', 'M')),
  nascimento        date not null,
  cargo             text not null,
  nivel_id          smallint not null references rh.niveis,
  area_id           smallint not null references rh.areas,
  unidade_id        smallint not null references rh.unidades,
  gestor_id         int references rh.colaboradores,
  admissao          date not null,
  desligamento      date,
  tipo_desligamento text check (tipo_desligamento in ('voluntario', 'involuntario')),
  salario           numeric(10, 2) not null,
  modalidade        text not null check (modalidade in ('presencial', 'hibrido', 'remoto')),
  check ((desligamento is null) = (tipo_desligamento is null))
);
create index colaboradores_area_idx   on rh.colaboradores (area_id);
create index colaboradores_gestor_idx on rh.colaboradores (gestor_id);

-- Ausências: só a quantidade de dias e o tipo. O motivo médico (CID)
-- nunca é guardado aqui: o painel não precisa dele.
create table rh.ausencias (
  id             bigint generated always as identity primary key,
  colaborador_id int not null references rh.colaboradores,
  data           date not null,
  dias           numeric(4, 1) not null check (dias > 0),
  tipo           text not null check (tipo in ('atestado', 'falta'))
);
create index ausencias_colab_idx on rh.ausencias (colaborador_id, data);

-- Pesquisa de clima: anônima pelo desenho. Não existe coluna que ligue
-- a resposta à pessoa, então nem quem administra o banco consegue saber
-- quem respondeu o quê.
create table rh.clima_respostas (
  id      bigint generated always as identity primary key,
  area_id smallint not null references rh.areas,
  ciclo   date not null,
  nota    smallint not null check (nota between 0 and 10)
);
create index clima_area_idx on rh.clima_respostas (area_id, ciclo);

-- ---------------------------------------------------------------------
-- Usuários do painel e auditoria
-- ---------------------------------------------------------------------
create table app.usuarios (
  id             smallint primary key,
  nome           text not null,
  email          text not null unique,
  senha_hash     text not null,
  perfil         text not null check (perfil in ('diretoria_rh', 'hrbp', 'gestor', 'analista')),
  cargo          text not null,
  diretoria_id   smallint references rh.diretorias,   -- escopo do HRBP
  colaborador_id int references rh.colaboradores      -- o gestor vê a própria equipe
);

create table app.acessos (
  id         bigint generated always as identity primary key,
  quando     timestamptz not null default now(),
  usuario_id smallint references app.usuarios,
  acao       text not null,
  detalhe    text,
  linhas     int
);
create index acessos_quando_idx on app.acessos (quando desc);

create table app.login_tentativas (
  id     bigint generated always as identity primary key,
  email  text not null,
  quando timestamptz not null default now(),
  ok     boolean not null
);
create index login_tentativas_idx on app.login_tentativas (email, quando desc);

create table app.atualizacoes (
  id      bigint generated always as identity primary key,
  quando  timestamptz not null default now(),
  origem  text not null,
  detalhe text
);

-- ---------------------------------------------------------------------
-- Área privada: segredo do token e parâmetros da simulação
-- ---------------------------------------------------------------------
create table app_privado.config (
  chave text primary key,
  valor text not null
);

create table app_privado.parametros_area (
  area_id          smallint primary key references rh.areas,
  rotulo           text not null,         -- como a área aparece no nome do cargo
  pct_mulheres     numeric not null,
  unidades         smallint[] not null,   -- sorteio ponderado (repetição = peso)
  qtd_niveis       int[] not null,        -- quantidade nos níveis 1 a 5 (o nível 6 é o gerente)
  saida_base       numeric not null,      -- chance mensal de desligamento
  saida_recente    numeric not null,      -- chance mensal depois do início da tendência
  pct_voluntario   numeric not null,
  atestado_base    numeric not null,      -- chance mensal de atestado por pessoa
  atestado_recente numeric not null,
  fator_salario    numeric not null,
  clima_media      numeric not null,      -- nota média na pesquisa de clima
  clima_queda      numeric not null,      -- quanto a nota cai a cada ciclo mais recente
  cargo_operacional text,                 -- 'Feminino|Masculino'
  crescimento      numeric not null default 0   -- chance mensal de abrir uma vaga nova
);

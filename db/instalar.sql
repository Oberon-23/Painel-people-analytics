create or replace function api.login(p_email text, p_senha text)
returns json language plpgsql volatile security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  u app.usuarios;
  falhas int;
  email_n text := lower(trim(p_email));
begin
  select count(*) into falhas from app.login_tentativas
   where email = email_n and not ok and quando > now() - interval '15 minutes';
  if falhas >= 5 then
    return json_build_object('ok', false, 'motivo', 'bloqueado');
  end if;

  select * into u from app.usuarios where email = email_n;
  if not found or u.senha_hash <> crypt(p_senha, u.senha_hash) then
    insert into app.login_tentativas (email, ok) values (email_n, false);
    return json_build_object('ok', false, 'motivo', 'invalido');
  end if;

  insert into app.login_tentativas (email, ok) values (email_n, true);
  insert into app.acessos (usuario_id, acao, detalhe) values (u.id, 'login', null);
  return json_build_object('ok', true, 'id', u.id);
end $$;

